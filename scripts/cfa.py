"""Command-line access to the CFA calculation library.

  python cfa.py list [topic]                       all formulas, or one topic's
  python cfa.py catalog                            Markdown catalog of every formula (references/calc-catalog.md)
  python cfa.py search <words>                     formulas whose name, formula or docstring match
  python cfa.py describe <name>                    signature, units, formula and curriculum source
  python cfa.py <name> key=value [key=value ...]   call it; values are JSON (0.05, [1,2], "text", true)
  python cfa.py <name> '{"key": value, ...}'       or pass one JSON object
  python cfa.py <name> @inputs.json                or a JSON file

Results print as JSON with full precision; --round N rounds floats for display only.
"""
from __future__ import annotations

import inspect
import json
import math
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from cfa_calc import REGISTRY, TOPICS  # noqa: E402


def _value(text: str):
    try:
        return json.loads(text)
    except json.JSONDecodeError:
        return text  # bare words stay strings: method=fifo


def parse_args(args: list[str]) -> dict:
    if len(args) == 1 and args[0].startswith("{"):
        return json.loads(args[0])
    if len(args) == 1 and args[0].startswith("@"):
        return json.loads(Path(args[0][1:]).read_text(encoding="utf-8"))
    out = {}
    for a in args:
        if "=" not in a:
            raise SystemExit(f"argument {a!r} is not key=value")
        k, v = a.split("=", 1)
        out[k.strip()] = _value(v.strip())
    return out


def _round(x, n: int | None):
    if n is None:
        return x
    if isinstance(x, float):
        return round(x, n) if math.isfinite(x) else x
    if isinstance(x, dict):
        return {k: _round(v, n) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_round(v, n) for v in x]
    return x


def _jsonable(x):
    if hasattr(x, "tolist"):  # numpy arrays and scalars
        return x.tolist()
    if isinstance(x, dict):
        return {str(k): _jsonable(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_jsonable(v) for v in x]
    return x


def describe(name: str) -> str:
    f = REGISTRY[name]
    doc = inspect.getdoc(f.func) or ""
    return (f"{name}{inspect.signature(f.func)}\n  topic: {f.topic}\n  formula: {f.formula}\n"
            f"  curriculum: {f.curriculum}\n\n{doc}\n")


def main(argv: list[str]) -> int:
    rnd = None
    if "--round" in argv:
        i = argv.index("--round")
        rnd = int(argv[i + 1])
        argv = argv[:i] + argv[i + 2:]
    if not argv or argv[0] in ("-h", "--help", "help"):
        print(__doc__)
        print("topics:", ", ".join(TOPICS))
        return 0
    cmd, rest = argv[0], argv[1:]
    if cmd == "list":
        topic = rest[0] if rest else None
        for name, f in sorted(REGISTRY.items(), key=lambda kv: (kv[1].topic, kv[0])):
            if topic in (None, f.topic):
                first = (inspect.getdoc(f.func) or "").split("\n")[0]
                print(f"{f.topic:18} {name:40} {first}")
        return 0
    if cmd == "catalog":
        print("# Calculation catalog\n\nGenerated by `python scripts/cfa.py catalog`; "
              "call any of these with `python scripts/cfa.py <name> key=value ...`.\n")
        for topic in TOPICS:
            items = sorted((n, f) for n, f in REGISTRY.items() if f.topic == topic)
            print(f"\n## {topic} ({len(items)})\n\n| Function | What it computes | Curriculum |\n|---|---|---|")
            for n, f in items:
                first = (inspect.getdoc(f.func) or "").split("\n")[0].replace("|", "/")
                print(f"| `{n}` | {first} | {f.curriculum.replace('|', '/')} |")
        return 0
    if cmd == "search":
        words = [w.lower() for w in rest]
        for name, f in sorted(REGISTRY.items()):
            hay = f"{name} {f.formula} {f.curriculum} {inspect.getdoc(f.func) or ''}".lower()
            if all(w in hay for w in words):
                print(f"{f.topic:18} {name:40} {(inspect.getdoc(f.func) or '').splitlines()[0] if f.func.__doc__ else ''}")
        return 0
    if cmd == "describe":
        print(describe(rest[0]))
        return 0
    if cmd not in REGISTRY:
        close = [n for n in REGISTRY if cmd.lower() in n.lower()]
        print(f"unknown formula {cmd!r}." + (f" Did you mean: {', '.join(sorted(close)[:10])}" if close else
                                             " Try: python cfa.py search <words>"), file=sys.stderr)
        return 2
    kwargs = parse_args(rest)
    try:
        result = REGISTRY[cmd].func(**kwargs)
    except (TypeError, ValueError) as exc:
        print(f"error: {exc}\n\n{describe(cmd)}", file=sys.stderr)
        return 1
    print(json.dumps(_round(_jsonable(result), rnd), indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
